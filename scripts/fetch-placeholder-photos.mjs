const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

/** Unsplash rate-limits its public endpoint; wait and retry on 429. */
async function fetchMeta(id) {
  for (let attempt = 0; attempt < 6; attempt++) {
    const res = await fetch(`https://unsplash.com/napi/photos/${id}`);
    if (res.status !== 429) return res.json();
    await sleep(15000 * (attempt + 1));
  }
  throw new Error(`still rate-limited for ${id}`);
}

const only = process.argv.slice(2);
const credits = [];
for (const [name, entry] of Object.entries(photos)) {
  if (only.length && !only.includes(name)) continue;
  const { id, rect } = typeof entry === 'string' ? { id: entry } : entry;
  await sleep(1500);
  const meta = await fetchMeta(id);
  if (meta.premium || meta.plus) {
    console.log(`SKIP ${name}: premium photo, not free to use`);
    continue;
  }
  const crop = rect
    ? `&rect=${[rect[0] * meta.width, rect[1] * meta.height, rect[2] * meta.width, rect[3] * meta.height].map(Math.round).join(',')}`
    : '';
  const res = await fetch(`${meta.urls.raw}${crop}&w=2000&q=78&fm=jpg&fit=max`);
  if (!res.ok) {
    console.log(`MISSING ${name} (${res.status})`);
    continue;
  }
  const buf = Buffer.from(await res.arrayBuffer());
  writeFileSync(join(out, `${name}.jpg`), buf);
  credits.push(`| \`${name}.jpg\` | ${meta.user.name} | https://unsplash.com/photos/${id} |`);
  console.log(`ok ${name} ${Math.round(buf.length / 1024)}KB`);
}

if (!only.length) {
  writeFileSync(
    join(out, 'CREDITS.md'),
    [
      '# Placeholder photo credits',
      '',
      'Unsplash licence (free for commercial use, no permission needed). Placeholders only:',
      'replace with Noorcom job photos before launch. Generated by `npm run photos`.',
      '',
      '| File | Photographer | Source |',
      '| --- | --- | --- |',
      ...credits,
      '',
    ].join('\n'),
  );
}
